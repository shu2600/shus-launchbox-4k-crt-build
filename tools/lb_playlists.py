"""Smart playlists for a LaunchBox library: best-rated per system plus themed collections, from the games already in Data\\Platforms.
Ratings are LaunchBox community ratings (CommunityStarRating + votes) already stored on each game."""
import os, re, uuid, xml.etree.ElementTree as ET

import os as _os, sys as _sys
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
import lbconfig as C  # paths from lb_settings.json

LB = C.LB
DATA = os.path.join(LB, "Data")
NS = uuid.UUID("2b7e1f4a-9c3d-4e5f-8a6b-1c2d3e4f5a6b")

games = []
for f in os.listdir(os.path.join(DATA, "Platforms")):
    for g in ET.parse(os.path.join(DATA, "Platforms", f)).getroot().findall("Game"):
        games.append({
            "id": g.findtext("ID"), "title": g.findtext("Title") or "", "platform": g.findtext("Platform") or "",
            "path": g.findtext("ApplicationPath") or "", "dbid": g.findtext("DatabaseID") or "",
            "genre": (g.findtext("Genre") or "").lower(), "rating": float(g.findtext("CommunityStarRating") or 0),
            "votes": int(g.findtext("CommunityStarRatingTotalVotes") or 0),
            "fav": (g.findtext("Favorite") or "").lower() == "true",
        })


def score(g):
    # Bayesian-ish: pull low-vote ratings towards 3.0 so one 5-star vote doesn't top the chart
    v, r = g["votes"], g["rating"]
    return (v * r + 10 * 3.0) / (v + 10) if v else 0


def write(name, items, category):
    root = ET.Element("LaunchBox")
    p = ET.SubElement(root, "Playlist")
    for k, v in [("PlaylistId", str(uuid.uuid5(NS, name))), ("Name", name), ("NestedName", name), ("SortBy", "Custom"),
                 ("IncludeWithPlatforms", "false"), ("AutoPopulate", "false"), ("IsAutogenerated", "false"),
                 ("HideInBigBox", "false"), ("Category", category), ("Notes", "Built from LaunchBox community ratings.")]:
        ET.SubElement(p, k).text = v
    for i, g in enumerate(items):
        e = ET.SubElement(root, "PlaylistGame")
        for k, v in [("GameId", g["id"]), ("LaunchBoxDbId", g["dbid"]), ("GameTitle", g["title"]),
                     ("GameFileName", os.path.splitext(os.path.basename(g["path"]))[0]), ("GamePlatform", g["platform"]),
                     ("ManualOrder", str(i))]:
            ET.SubElement(e, k).text = v
    ET.indent(root, space="  ")
    safe = re.sub(r'[\\/:*?"<>|\']', "_", name)   # LaunchBox's own file naming: Beat 'em Ups -> Beat _em Ups.xml
    with open(os.path.join(DATA, "Playlists", f"{safe}.xml"), "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" standalone="yes"?>\n' + ET.tostring(root, encoding="unicode") + "\n")
    print(f"{name}: {len(items)}")


def favs_first(pool, n):
    """Your favourites (LaunchBox's Favorite tick) at the top, then the best-rated games, one entry per title,
    so the same game under two set names (Pac-Man / Puckman) only shows once. Favourites always make the list."""
    ranked = sorted([g for g in pool if g["fav"]], key=score, reverse=True) + \
             sorted([g for g in pool if not g["fav"] and g["votes"] >= 5], key=score, reverse=True)
    out, seen = [], set()
    for g in ranked:
        key = g["title"].lower()
        if key in seen:
            continue
        seen.add(key)
        out.append(g)
    favs = sum(1 for g in out if g["fav"])
    return out[:max(n, favs)]


rated = [g for g in games if g["votes"] >= 5]
# 1. Best of each system (top 50, needs 5+ votes; your favourites from that system always at the top)
for plat in sorted({g["platform"] for g in rated} | {g["platform"] for g in games if g["fav"]}):
    top = favs_first([g for g in games if g["platform"] == plat], 50)
    if len(top) >= 10:
        write(f"Best of {plat}", top, "Best of Each System")

def _norm(t):
    t = re.sub(r"\(.*?\)|\[.*?\]", "", t.lower().replace("&", "and"))
    t = re.sub(r",\s*the$", "", t.strip())
    return re.sub(r"[^a-z0-9]", "", re.sub(r"^the\s+", "", t))


def curated(plat):
    """top_lists/<Platform>.txt: a researched top list, one title per line (# = comment), best first."""
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "top_lists", f"{plat}.txt")
    if not os.path.exists(p):
        return []
    return [l.strip() for l in open(p, encoding="utf-8") if l.strip() and not l.startswith("#")]


# 1b. Top 100 <system>: your favourites first, then the researched top list in its order (top_lists/), then the
#     best-rated games to fill up to 100. Arcade always gets one; other systems once they have a top list.
for plat in sorted({g["platform"] for g in games}):
    pool = [g for g in games if g["platform"] == plat]
    wanted = curated(plat)
    if plat != "Arcade" and not wanted:
        continue
    by_title = {}
    for g in sorted(pool, key=score, reverse=True):
        by_title.setdefault(_norm(g["title"]), g)
    picks = [by_title[_norm(t)] for t in wanted if _norm(t) in by_title]
    favs = [g for g in favs_first(pool, 0) if g["fav"]]
    out, seen = [], set()
    for g in favs + picks + favs_first(pool, 100):
        k = _norm(g["title"])
        if k not in seen:
            seen.add(k)
            out.append(g)
    write(f"Top 100 {plat}", out[:max(100, len(favs))], "Best of Each System")

# 2. All-time top 100 across everything
write("Top 100 of All Time", sorted([g for g in rated if g["votes"] >= 20], key=score, reverse=True)[:100], "Collections")


def theme(name, pred, n=200, min_votes=0):
    items = sorted([g for g in games if pred(g) and g["votes"] >= min_votes], key=score, reverse=True)[:n]
    if items:
        write(name, items, "Collections")


T = lambda pat: (lambda g: re.search(pat, g["title"], re.I) is not None)
theme("Boxing", lambda g: T(r"\b(boxing|knockout kings|fight night|punch-out|ready 2 rumble|frank bruno|title fight)\b")(g)
      or ("boxing" in g["genre"]))
theme("Football", lambda g: T(r"\b(soccer|football|sensible|kick off|fifa|pro evolution|pes \d|iss\b|match day|player manager|emlyn hughes|goal!|world cup|virtua striker|winning eleven|championship manager)\b")(g)
      and "american" not in g["genre"] and "shooter" not in g["genre"] and not re.search(r"mutant league|tecmo bowl|madden|nfl", g["title"], re.I))
theme("Beat 'em Ups", lambda g: "beat" in g["genre"] and "up" in g["genre"], 150, 5)
theme("Fighting Games", lambda g: "fighting" in g["genre"], 150, 5)
theme("Shoot 'em Ups", lambda g: "shooter" in g["genre"] and ("vertical" in g["genre"] or "horizontal" in g["genre"] or "shmup" in g["genre"]), 150, 5)
theme("Racing", lambda g: "racing" in g["genre"] or "driving" in g["genre"], 150, 5)
theme("Platformers", lambda g: "platform" in g["genre"], 150, 5)
theme("Speccy Classics", lambda g: g["platform"] == "Sinclair ZX Spectrum", 100, 3)
theme("Amiga Classics", lambda g: g["platform"] == "Commodore Amiga", 100, 3)
theme("Pinball", lambda g: g["platform"] in ("Pinball", "Visual Pinball X") or "pinball" in g["genre"], 200)

GUNROMS = set()
for _e, _el in ET.iterparse(os.path.join(LB, r"Metadata\MAME.xml")):
    if _el.tag == "MameFile":
        if "gun" in (_el.findtext("Genre") or "").lower():
            GUNROMS.add((_el.findtext("FileName") or "").lower())
        _el.clear()
theme("Lightgun Games", lambda g: g["platform"] == "Arcade" and (os.path.splitext(os.path.basename(g["path"]))[0].lower() in GUNROMS or "gun" in g["genre"] or re.search(r"area 51|maximum force|carnevil|crypt killer|time crisis|house of the dead|lethal enforcers|operation wolf|duck hunt|point blank|big buck", g["title"], re.I)), 200)
theme("Driving (Arcade)", lambda g: g["platform"] == "Arcade" and ("driving" in g["genre"] or "racing" in g["genre"]), 240)
